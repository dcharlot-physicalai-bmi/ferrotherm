/// Board-level pins of the Alchitry Pt V2, bank 14, `LVCMOS33`.
const CLOCK_PIN: &str = "W19";
const RESET_PIN: &str = "N15";
const LED_PINS: [&str; 8] = ["P19", "P20", "T21", "R19", "V22", "U21", "T20", "W20"];
/// The board's oscillator, nanoseconds.
const CLOCK_PERIOD_NS: f64 = 10.0;
/// `XC7A100T-2FGG484I` as Vivado names it.
const PT_PART: &str = "xc7a100tfgg484-2";
/// `XCK26-SFVC784-2LV` as Vivado names it, with the board part the block design needs.
const KV260_PART: &str = "xck26-sfvc784-2LV-c";
const KV260_BOARD: &str = "xilinx.com:kv260_som:part0:2.0";

/// A top module that runs `core` and cannot be optimised away: every state bit folds into one
/// registered bit, which clocks a counter, whose high bits drive the LEDs.
fn top(module: &str, core: &str, state_width: usize, phase_width: usize) -> String {
    format!(
        r#"// generated by ferrotherm::examples::alchitry_pt_build -- Alchitry Pt V2 top
module {module} (
    input  wire clk,
    input  wire rst_n,
    output reg  [7:0] led
);
  wire rst = ~rst_n;
  wire [{state_top}:0] state;
  wire [{phase_top}:0] phase;
  (* DONT_TOUCH = "true" *)
  {core} core (.clk(clk), .rst(rst), .en(1'b1), .state(state), .phase(phase));

  // The sink. Without something a port can reach, synthesis deletes the fabric and the board
  // measures a design that is not there.
  (* DONT_TOUCH = "true" *)
  reg fold = 1'b0;
  always @(posedge clk) fold <= ^state;

  // A fabric that is sampling toggles `fold`; one that has frozen does not, so the LEDs report
  // the difference rather than merely reporting power.
  reg [31:0] beat = 32'd0;
  always @(posedge clk) begin
    if (rst) beat <= 32'd0;
    else if (fold) beat <= beat + 32'd1;
  end
  always @(posedge clk) led <= beat[31:24];
endmodule
"#,
        state_top = state_width - 1,
        phase_top = phase_width - 1,
    )
}

/// The pin constraints and the clock period.
fn xdc() -> String {
    let mut s = String::from("# Alchitry Pt V2 -- board-level pins, bank 14, LVCMOS33\n");
    s.push_str(&format!(
        "set_property -dict {{PACKAGE_PIN {CLOCK_PIN} IOSTANDARD LVCMOS33}} [get_ports clk]\n\
         create_clock -period {CLOCK_PERIOD_NS:.3} -name sys_clk [get_ports clk]\n\
         set_property -dict {{PACKAGE_PIN {RESET_PIN} IOSTANDARD LVCMOS33}} [get_ports rst_n]\n"
    ));
    for (i, pin) in LED_PINS.iter().enumerate() {
        s.push_str(&format!(
            "set_property -dict {{PACKAGE_PIN {pin} IOSTANDARD LVCMOS33}} [get_ports {{led[{i}]}}]\n"
        ));
    }
    s.push_str(
        "\n# The configuration bank, so the bitstream loads rather than merely building.\n\
         set_property CFGBVS VCCO [current_design]\n\
         set_property CONFIG_VOLTAGE 3.3 [current_design]\n",
    );
    s
}

/// A Vivado script: synthesise, implement, report what it cost, and write the bitstream.
fn tcl(name: &str, core_file: &str) -> String {
    format!(
        r#"# generated by ferrotherm::examples::alchitry_pt_build
read_verilog {{{core_file} top_{name}.v}}
read_xdc pt_v2.xdc
synth_design -top top_{name} -part {PT_PART}
report_utilization -file {name}_utilization_synth.rpt
opt_design
place_design
phys_opt_design
route_design
report_utilization -file {name}_utilization.rpt
report_timing_summary -max_paths 5 -file {name}_timing.rpt
write_bitstream -force {name}.bit
puts "FERROTHERM_BUILD_DONE {name}"
"#
    )
}

/// The KV260 top: no programmable-logic I/O, the processing system's clock, and every state bit
/// folded into one registered bit -- the arrangement the board's 10.85 pJ per flip was metered
/// through. `DONT_TOUCH` on the instance and on the fold, because a fabric that no port can
/// reach is trimmed to about one lookup table and the board then measures a correct zero for a
/// design that is not there.
fn kv260_top(module: &str, core: &str, state_width: usize, phase_width: usize) -> String {
    format!(
        r#"// generated by ferrotherm::examples::board_build -- Kria KV260 power-measurement top
module {module}(input wire clk);
  reg [7:0] por = 8'hFF;
  always @(posedge clk) if (por != 8'd0) por <= por - 8'd1;
  wire rst = (por != 8'd0);
  (* DONT_TOUCH="true" *) wire [{state_top}:0] state;
  wire [{phase_top}:0] phase;
  (* DONT_TOUCH="true" *) {core} u_fabric (.clk(clk), .rst(rst), .en(1'b1), .state(state), .phase(phase));
  (* DONT_TOUCH="true" *) reg keep;
  always @(posedge clk) keep <= ^state;
endmodule

module design_{core}();
  wire pl_clk0;
  sys_wrapper ps_i (.pl_clk0(pl_clk0));
  {module}    u    (.clk(pl_clk0));
endmodule
"#,
        state_top = state_width - 1,
        phase_top = phase_width - 1,
    )
}

