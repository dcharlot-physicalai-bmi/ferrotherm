/// The host side of a metered read: one process, three arms, the fabric free-running in all of
/// them so that it is in every baseline.
fn host_reader_c(n_words: usize) -> String {
    format!(
        r#"// generated by ferrotherm::examples::board_build -- the host side of a metered read
// usage: ft_read <idle|halt|cpu|axi> <seconds>
//   idle  the fabric runs; this process sleeps.
//   halt  the fabric is HELD (run = 0: spins and generators frozen, clock still toggling); this
//         process sleeps. idle minus halt is the fabric's datapath power on ONE placement, with no
//         reload between the arms. Its known answer is zero sweeps per second.
//   cpu   the fabric runs; one core spins the SAME loop over {n_words} words of its own memory.
//   axi   the fabric runs; one core reads the fabric's {n_words} state words over AXI4-Lite.
// Every arm starts the fabric and reads the sweep counter before and after, so every arm reports
// a clock rate with a known answer: 100 MHz and two clocks a sweep is 5.0e7 sweeps per second. A
// port whose data width disagrees with the PS returns words that fail that, loudly.
#include <fcntl.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>
#include <time.h>
#include <unistd.h>
#define BASE 0xA0000000UL
#define NW {n_words}
static double now(void) {{ struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + 1e-9 * t.tv_nsec; }}
int main(int argc, char **argv) {{
  if (argc != 3) {{ fprintf(stderr, "usage: ft_read <idle|halt|cpu|axi> <seconds>\n"); return 2; }}
  double secs = atof(argv[2]);
  int fd = open("/dev/mem", O_RDWR | O_SYNC);
  if (fd < 0) {{ perror("/dev/mem"); return 1; }}
  volatile uint32_t *r = mmap(0, 4096, PROT_READ | PROT_WRITE, MAP_SHARED, fd, BASE);
  if (r == MAP_FAILED) {{ perror("mmap"); return 1; }}
  r[2] = 0;          // target 0: free-run
  r[0] = (argv[1][0] == 'h') ? 0 : 1;   // run, or hold
  static volatile uint32_t local[NW];
  for (int k = 0; k < NW; k++) local[k] = 0x9E3779B9u * (k + 1);
  uint64_t reads = 0, pop_sum = 0; uint32_t pop_min = ~0u, pop_max = 0, acc = 0, changed = 0, prev0 = r[8];
  // The sweep counter is 32 bits at 5e7 a second: it wraps every 86 s, so it is differenced in
  // windows far shorter than that rather than once across the arm.
  uint32_t s_prev = r[3]; uint64_t sweeps = 0;
  double t0 = now(), t = t0, t_end = t0 + secs;
  while (t < t_end) {{
    if (argv[1][0] == 'a') {{
      for (int rep = 0; rep < 256; rep++) for (int k = 0; k < NW; k++) acc ^= r[8 + k];
      reads += 256ull * NW;
    }} else if (argv[1][0] == 'c') {{
      for (int rep = 0; rep < 256; rep++) for (int k = 0; k < NW; k++) acc ^= local[k];
      reads += 256ull * NW;
    }} else {{
      usleep(200000);
    }}
    uint32_t s_now = r[3]; sweeps += (uint32_t)(s_now - s_prev); s_prev = s_now;
    uint32_t p = r[4]; pop_sum += p; if (p < pop_min) pop_min = p; if (p > pop_max) pop_max = p;
    uint32_t w0 = r[8]; if (w0 != prev0) changed++; prev0 = w0;
    t = now();
  }}
  double dt = t - t0;
  printf("arm=%s seconds=%.6f word_reads=%llu reads_per_s=%.1f sweeps=%llu sweeps_per_s=%.1f pop_min=%u pop_max=%u word0_changes=%u acc=%08x\n",
         argv[1], dt, (unsigned long long)reads, reads / dt, (unsigned long long)sweeps, sweeps / dt, pop_min, pop_max, changed, acc);
  return 0;
}}
"#
    )
}

/// The protocol: interleaved arms in a random order per pass, the sensor sampled by the same code
/// in every arm, and three ways to refuse.
fn meter_protocol_py(bitstream: &str, hpm0_width: u32) -> String {
    let afi = match hpm0_width { 32 => 0, 64 => 1, _ => 2 };
    format!(
        r##"#!/usr/bin/env python3
# generated by ferrotherm::examples::board_build -- meter a READ on a KV260
# usage: sudo python3 meter_read.py [passes] [settle_s] [sample_s] [arms, default idle,cpu,axi]
# Writes one row per sensor sample and one row per arm. Refuses, rather than measuring, when:
#   - the PS's HPM0 data width is not the {hpm0_width} bits this bitstream was built for;
#   - dmesg does not show THIS bitstream going in (a failed load leaves the old design running
#     with state=operating, and a read of an address no slave answers can take the board down);
#   - another session's measurement is running on this shared board.
# And flags, rather than hides, any pass during which someone else loaded the FPGA.
import os, random, subprocess, sys, time
BIT = "{bitstream}"
HW = "/sys/class/hwmon/hwmon2/power1_input"
passes = int(sys.argv[1]) if len(sys.argv) > 1 else 8
settle = float(sys.argv[2]) if len(sys.argv) > 2 else 15.0
sample = float(sys.argv[3]) if len(sys.argv) > 3 else 25.0
ARMS = (sys.argv[4] if len(sys.argv) > 4 else "idle,cpu,axi").split(",")
def sh(c): return subprocess.run(c, shell=True, capture_output=True, text=True).stdout
def loads(): return int(sh("dmesg | grep -c 'writing.*FPGA'").strip() or 0)
def foreign(): return sh("pgrep -af 'kv_|flashv|flash8|flashfull' | grep -v pgrep").strip()
if foreign():
    sys.exit("REFUSED: another session is measuring on this board:\n" + foreign())
afi = int(sh("busybox devmem 0xFD615000 32").strip(), 16)
if (afi >> 8) & 3 != {afi}:
    sys.exit("REFUSED: afi_fs=%#x, HPM0 is not {hpm0_width} bits wide; this bitstream would read garbage" % afi)
before = int(sh("dmesg | grep -c 'writing %s'" % BIT).strip() or 0)
open("/sys/class/fpga_manager/fpga0/firmware", "w").write(BIT)
time.sleep(5)
after = int(sh("dmesg | grep -c 'writing %s'" % BIT).strip() or 0)
if after <= before:
    sys.exit("REFUSED: LOAD-NOOP, dmesg shows no write of " + BIT)
print("# meter_read bitstream=%s passes=%d settle=%.0f sample=%.0f afi_fs=%#x" % (BIT, passes, settle, sample, afi), flush=True)
for p in range(1, passes + 1):
    order = list(ARMS); random.shuffle(order)
    for arm in order:
        if foreign():
            print("# ABORTED pass=%d: another session started measuring" % p, flush=True); sys.exit(3)
        l0 = loads()
        proc = subprocess.Popen(["taskset", "-c", "3", "./ft_read", arm, str(settle + sample)], stdout=subprocess.PIPE, text=True)
        time.sleep(settle)
        t_end = time.time() + sample - 1.0
        while time.time() < t_end:
            print("S %d %s %s" % (p, arm, open(HW).read().strip()), flush=True)
            time.sleep(0.25)
        out = proc.communicate()[0].strip()
        print("A %d %s" % (p, out), flush=True)
        if loads() != l0:
            print("# FOREIGN-LOAD pass=%d arm=%s" % (p, arm), flush=True)
print("# done", flush=True)
"##
    )
}

/// Out-of-context synthesis of both fabrics: utilization without a board, which is the fastest
/// honest answer to what a unit costs on a part.
fn ooc_tcl(part: &str) -> String {
    format!(
        r#"# generated by ferrotherm::examples::board_build -- utilization only, no board needed
set part {part}
foreach {{src top}} {{pdit.v pdit pbit.v pbit}} {{
  puts "=== SYNTH $top ($src) ==="
  read_verilog $src
  synth_design -top $top -part $part -mode out_of_context
  puts "--- UTIL $top ---"
  report_utilization
  puts "=== DONE $top ==="
  close_design
}}
exit
"#
    )
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let board = args.get(1).map_or("alchitry-pt", String::as_str);
    let out = args.get(2).map_or("build/board", String::as_str);
    let pdit_sites: usize = args.get(3).map_or(16, |v| v.parse().expect("a site count"));
    let pbit_side: usize = args.get(4).map_or(8, |v| v.parse().expect("a lattice side"));
    let rom_bits: u32 = args.get(5).map_or(10, |v| v.parse().expect("ROM bits"));
    let part = match board {
        "alchitry-pt" => PT_PART,
        "kv260" | "kv260-axi" => KV260_PART,
        other => {
            eprintln!("unknown board {other}: expected alchitry-pt, kv260 or kv260-axi");
            std::process::exit(2);
        }
    };
    let dir = Path::new(out);
    fs::create_dir_all(dir).expect("output directory");

    // A three-state Potts ring, hot enough that the fabric keeps moving: a frozen fabric draws
    // the power of a fabric that is not sampling, and measures nothing.
    let potts = ring(pdit_sites, 3, 1.0, Interaction::Potts);
    let trit = FixedPdit::new(&potts, 0.6, 1, rom_bits).expect("a Potts ring");
    let sb = trit.state_bits();
    let pb = trit.phase_bits();
    fs::write(dir.join("pdit.v"), trit.emit_verilog("pdit")).expect("write");

    // A p-bit lattice, the fabric this crate metered on a KV260 at 10.85 pJ per flip.
    let g = lattice2d(pbit_side, 1.0);
    let bit = FixedFabric::new(&g, 0.6, 1);
    fs::write(dir.join("pbit.v"), bit.emit_verilog("pbit")).expect("write");

    // Utilization needs no board, and is the fastest honest answer to what a unit costs.
    fs::write(dir.join("ooc.tcl"), ooc_tcl(part)).expect("write");

    match board {
        "alchitry-pt" => {
            fs::write(dir.join("top_pdit.v"), top("top_pdit", "pdit", trit.n * sb, pb)).expect("write");
            fs::write(dir.join("top_pbit.v"), top("top_pbit", "pbit", g.n, 1)).expect("write");
            fs::write(dir.join("pdit.tcl"), tcl("pdit", "pdit.v")).expect("write");
            fs::write(dir.join("pbit.tcl"), tcl("pbit", "pbit.v")).expect("write");
            fs::write(dir.join("pt_v2.xdc"), xdc()).expect("write");
        }
        "kv260-axi" => {
            // What the running PS had in `afi_fs` on the board this was written against. The
            // protocol reads the register back and refuses if the board disagrees.
            let hpm0_width = 128;
            fs::write(dir.join("ft_axi.v"), bit.emit_axi_shell("ft_axi", "pbit", "clk")).expect("write");
            fs::write(dir.join("ft_axi_bd.v"), kv260_axi_wrapper()).expect("write");
            fs::write(dir.join("axi.tcl"), kv260_axi_tcl(hpm0_width)).expect("write");
            fs::write(dir.join("ft_read.c"), host_reader_c(g.n.div_ceil(32))).expect("write");
            fs::write(dir.join("meter_read.py"), meter_protocol_py("ft_axi.bit.bin", hpm0_width)).expect("write");
            fs::write(dir.join("ft_axi.bif"), "all:\n{\n  [destination_device = pl] ft_axi.bit\n}\n").expect("write");
        }
        _ => {
            fs::write(dir.join("kv260_top_pdit.v"), kv260_top("kv260_top_pdit", "pdit", trit.n * sb, pb)).expect("write");
            fs::write(dir.join("kv260_top_pbit.v"), kv260_top("kv260_top_pbit", "pbit", g.n, 1)).expect("write");
            fs::write(dir.join("pdit.tcl"), kv260_tcl("pdit", "pdit.v")).expect("write");
            fs::write(dir.join("pbit.tcl"), kv260_tcl("pbit", "pbit.v")).expect("write");
        }
    }

    println!("{board} ({part}) build written to {out}");
    println!(
        "  p-trit fabric: {} sites of radix {}, {} state bits each, {} colour classes, {rom_bits}-bit Gumbel ROM",
        trit.n,
        trit.q,
        sb,
        trit.classes.len()
    );
    println!(
        "  p-bit fabric:  {} spins on a {pbit_side}x{pbit_side} lattice, {} colour classes",
        g.n,
        g.classes.len()
    );
    println!();
    println!("ooc.tcl reports what each unit costs on this part; the per-board scripts implement");
    println!("and write a bitstream. Divide the utilization by the unit count, and read the");
    println!("timing summary for the clock the part will hold.");
}
