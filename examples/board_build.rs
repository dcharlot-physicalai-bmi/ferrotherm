//! Emit a board build for a real FPGA -- the **Alchitry Pt V2** (`XC7A100T-2FGG484I`) or the
//! **Kria KV260** (`XCK26-SFVC784-2LV`): a p-trit fabric and a p-bit fabric, each wrapped in a
//! top module that board can actually run, with the constraints and the Vivado scripts that say
//! what each unit costs in real silicon.
//!
//! ```text
//!   cargo run --release --example board_build -- <alchitry-pt|kv260|kv260-axi> <outdir> [pdit-sites] [pbit-side] [rom-bits]
//! ```
//!
//! # What this is for
//!
//! `examples/pdit_synth.rs` prices the two fabrics in yosys's generic cells, which is a ratio and
//! not a part: 4,027 cells per p-trit against 173 per p-bit, most of the p-trit's being three
//! Gumbel ROMs that are addressed by noise and so cannot constant-fold. A generic cell is not a
//! LUT6, and an FPGA's block RAM changes the answer again. This emits the same two fabrics for a
//! real device so Vivado can say what they cost there, and writes a bitstream that runs.
//!
//! # The two traps this is shaped around, both paid for once already
//!
//! **A fabric with no observable sink is deleted.** Synthesis keeps what reaches a port. The
//! p-bit fabric's own state is read by nothing, so an unwrapped instance optimises away to
//! almost nothing and a board then measures a correct zero for a design that is not there. Every
//! state bit is folded into one registered bit here, that bit drives a counter, and the counter
//! drives the LEDs -- and both the fabric instance and the fold carry `DONT_TOUCH`.
//!
//! **A frozen fabric measures nothing.** The couplings are written at a temperature where the
//! spins keep moving, so the LEDs report a fabric that is sampling rather than one that has
//! settled; `beta` is a parameter here for that reason.
//!
//! # The two boards
//!
//! **Alchitry Pt V2.** Board-level pins from the Alchitry Labs V2 source
//! (`hardware/pinout/PtV2TopPin.kt`, read 2026-09-15), all bank 14 at `LVCMOS33`: clock `W19`
//! (100 MHz), reset `N15` (active low), LEDs `P19 P20 T21 R19 V22 U21 T20 W20`. The first-batch
//! boards carry a pinout erratum on the TOP expansion connector; it does not touch these, which
//! are board-level. Artix-7 is not in every Vivado install -- check `get_parts xc7a*` before
//! building.
//!
//! **Kria KV260.** No programmable-logic I/O at all: the processing system supplies `pl_clk0` at
//! 100 MHz and the fabric toggles internally, which is the arrangement the 10.85 pJ per flip in
//! [`crate::ledger::KV260_MEASURED`] was metered through. `build.tcl` builds the block design
//! that provides that clock; the board's own INA260 on the 5 V rail is the instrument.
//!
//! **Kria KV260 with a read path (`kv260-axi`).** The build above has NO way to read a spin: its
//! block design disables every PS-to-PL AXI master, which is why that measurement could price a
//! flip and had to leave `e_read` unstated. This variant hangs [`FixedFabric::emit_axi_shell`] off
//! `M_AXI_HPM0_FPD` at `0xA000_0000`, and emits the host program and the protocol that meter a
//! read. Two things it is shaped around. The port's DATA WIDTH is a PS register (`afi_fs`,
//! `0xFD61_5000`) that the boot firmware sets and a bare `fpga_manager` load does not touch: on
//! the board this was written against it read `0xA00`, 128 bits, so the design says 128 and the
//! protocol reads the register back and refuses on a mismatch. And a read of a PL address NO
//! SLAVE ANSWERS can take the board down, so the host program is never pointed at the fabric until
//! `dmesg` shows this bitstream went in.

